//! Oracle tests for the M10 path-dependent TreeSHAP engine (TIGHT tier).
//!
//! Rebuild each fixture's forest by importing every tree via
//! [`Tree::from_sklearn`] into a [`RandomForest`], run [`RandomForest::tree_shap`]
//! on the fixture's query table, and assert the `base_values` + per-sample
//! `shap_values` reproduce the Python `shap` library's path-dependent
//! `TreeExplainer` at the per-fixture tolerance. The additivity identity
//! (`base + Σ shap == predict_proba` / `predict_values`) is also re-checked
//! in-test, independent of the fixture.
//!
//! Hermetic: no Python, no network — just the committed fixtures generated by
//! `oracle/generator/gen_shap.py` against `qiime2-amplicon-2024.10` + `shap`.

use sc_core::{FeatureMatrix, RandomForest, Task, Tree};
use sc_oracle::{load_dir, CooTable, OracleCase, Payload};

fn fixtures() -> Vec<OracleCase> {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../oracle/fixtures/shap");
    let cases = load_dir(dir);
    assert!(!cases.is_empty(), "no fixtures loaded from {dir}");
    cases
}

fn query_matrix(coo: &CooTable) -> FeatureMatrix {
    FeatureMatrix::from_coo(
        coo.n_samples,
        coo.n_features,
        &coo.rows,
        &coo.cols,
        &coo.vals,
    )
    .expect("valid COO")
}

#[test]
fn classifier_shap_matches_oracle() {
    let mut n = 0;
    for case in fixtures() {
        let Payload::ForestShapClassifier(c) = &case.payload else {
            continue;
        };
        n += 1;
        let (id, tol) = (&case.id, &case.tolerance);
        let trees: Vec<Tree> = c
            .trees
            .iter()
            .map(|t| {
                let value: Vec<f64> = t.value.iter().flatten().copied().collect();
                Tree::from_sklearn(
                    Task::Classification {
                        n_classes: c.n_classes,
                    },
                    &t.children_left,
                    &t.children_right,
                    &t.feature,
                    &t.threshold,
                    &value,
                    &t.impurity,
                    &t.n_node_samples,
                    &t.weighted_n_node_samples,
                    c.n_features,
                )
                .unwrap_or_else(|e| panic!("{id}: from_sklearn failed: {e}"))
            })
            .collect();
        let forest = RandomForest::from_trees(trees, Some(c.classes.clone()))
            .unwrap_or_else(|e| panic!("{id}: from_trees failed: {e}"));

        let x = query_matrix(&c.test_coo);
        let shap = forest.tree_shap(&x).unwrap();
        assert_eq!(shap.n_outputs, c.n_classes, "{id}: n_outputs");
        assert_eq!(shap.n_features, c.n_features, "{id}: n_features");

        sc_oracle::assert_close_slice(
            &shap.base_values,
            &c.expected.base_values,
            tol,
            &format!("{id}: base_values"),
        );
        assert_eq!(
            shap.values.len(),
            c.expected.shap_values.len(),
            "{id}: sample count"
        );
        // shap.values[s] is [class][feature] — the fixture's canonical layout.
        for (s, (got, want)) in shap.values.iter().zip(&c.expected.shap_values).enumerate() {
            sc_oracle::assert_close_matrix(got, want, tol, &format!("{id}: shap[{s}]"));
        }

        // Additivity: base + Σ_f shap == predict_proba, per sample/class.
        let proba = forest.predict_proba(&x).unwrap();
        for (s, prow) in proba.iter().enumerate() {
            for (o, &p) in prow.iter().enumerate() {
                let recon: f64 = shap.base_values[o] + shap.values[s][o].iter().sum::<f64>();
                assert!(
                    (recon - p).abs() <= 1e-9,
                    "{id}: additivity[{s}][{o}] {recon} vs proba {p}"
                );
            }
        }
    }
    assert!(n >= 2, "expected >=2 shap classifier fixtures, saw {n}");
}

#[test]
fn regressor_shap_matches_oracle() {
    let mut n = 0;
    for case in fixtures() {
        let Payload::ForestShapRegressor(c) = &case.payload else {
            continue;
        };
        n += 1;
        let (id, tol) = (&case.id, &case.tolerance);
        let trees: Vec<Tree> = c
            .trees
            .iter()
            .map(|t| {
                Tree::from_sklearn(
                    Task::Regression,
                    &t.children_left,
                    &t.children_right,
                    &t.feature,
                    &t.threshold,
                    &t.value,
                    &t.impurity,
                    &t.n_node_samples,
                    &t.weighted_n_node_samples,
                    c.n_features,
                )
                .unwrap_or_else(|e| panic!("{id}: from_sklearn failed: {e}"))
            })
            .collect();
        let forest = RandomForest::from_trees(trees, None)
            .unwrap_or_else(|e| panic!("{id}: from_trees failed: {e}"));

        let x = query_matrix(&c.test_coo);
        let shap = forest.tree_shap(&x).unwrap();
        assert_eq!(shap.n_outputs, 1, "{id}: n_outputs");
        assert_eq!(shap.n_features, c.n_features, "{id}: n_features");

        sc_oracle::assert_close(
            shap.base_values[0],
            c.expected.base_value,
            tol,
            &format!("{id}: base_value"),
        );
        assert_eq!(
            shap.values.len(),
            c.expected.shap_values.len(),
            "{id}: sample count"
        );
        // shap.values[s][0] is the [feature] row (single output).
        for (s, (got, want)) in shap.values.iter().zip(&c.expected.shap_values).enumerate() {
            sc_oracle::assert_close_slice(&got[0], want, tol, &format!("{id}: shap[{s}]"));
        }

        let pred = forest.predict_values(&x).unwrap();
        for (s, &p) in pred.iter().enumerate() {
            let recon: f64 = shap.base_values[0] + shap.values[s][0].iter().sum::<f64>();
            assert!(
                (recon - p).abs() <= 1e-9,
                "{id}: additivity[{s}] {recon} vs predict {p}"
            );
        }
    }
    assert!(n >= 1, "expected >=1 shap regressor fixture, saw {n}");
}

#[test]
fn aggregate_scores_within_calibrated_band() {
    let mut scored = 0;
    let mut invariant = 0;
    for case in fixtures() {
        let Payload::ForestAggregate(c) = &case.payload else {
            continue;
        };
        let id = &case.id;
        let x = query_matrix(&c.data_coo);
        let y = build_targets(c);
        let x_train = x.select_rows(&c.train_idx);
        let y_train = y.select(&c.train_idx);
        let x_test = x.select_rows(&c.test_idx);

        let mut params = match c.task.as_str() {
            "classification" => RandomForestParams::classifier_defaults(),
            "regression" => RandomForestParams::regressor_defaults(),
            other => panic!("{id}: unexpected task {other}"),
        };
        params.n_estimators = c.n_estimators;
        // Deterministic under a fixed master seed → the whole test is deterministic.
        let forest = RandomForest::fit(&x_train, &y_train, &params, 0)
            .unwrap_or_else(|e| panic!("{id}: fit failed: {e}"));

        if c.band.is_invariant() {
            invariant += 1;
            assert_invariants(id, &forest, &x_test, c);
            continue;
        }
        scored += 1;

        match c.task.as_str() {
            "classification" => {
                let y_test = y.select(&c.test_idx);
                let truth = y_test.codes().expect("categorical test codes");
                let pred = forest.predict_class_indices(&x_test).unwrap();
                let acc = accuracy(truth, &pred);
                assert!(
                    c.band.contains(acc),
                    "{id}: accuracy {acc:.4} outside band [{}, {}] (+/- margin {})",
                    c.band.min,
                    c.band.max,
                    c.band.margin_abs
                );
            }
            "regression" => {
                let y_test = y.select(&c.test_idx);
                let Targets::Numeric(truth) = &y_test else {
                    panic!("{id}: expected numeric test targets");
                };
                let pred = forest.predict_values(&x_test).unwrap();
                let rep = linear_regress(truth, &pred);
                assert!(
                    c.band.contains(rep.r_squared),
                    "{id}: r2 {:.4} outside band [{}, {}]",
                    rep.r_squared,
                    c.band.min,
                    c.band.max
                );
                let mse_band = c.mse_band.as_ref().expect("regression carries an mse band");
                assert!(
                    mse_band.contains(rep.mse),
                    "{id}: mse {:.4} outside band [{}, {}]",
                    rep.mse,
                    mse_band.min,
                    mse_band.max
                );
            }
            other => panic!("{id}: unexpected task {other}"),
        }

        // Importance ranking is rank-correlated with sklearn's seed-mean.
        let ours = forest.feature_importances();
        let rho = spearman(&ours, &c.ref_importances);
        let floor = c.rank_corr_floor - c.rank_corr_margin;
        assert!(
            rho >= floor,
            "{id}: importance rank-corr {rho:.4} < floor {floor:.4} \
             (sklearn min-pairwise {:.4} - margin {})",
            c.rank_corr_floor,
            c.rank_corr_margin
        );
    }
    assert!(
        scored >= 4,
        "expected >=4 scored aggregate cases, saw {scored}"
    );
    assert!(
        invariant >= 3,
        "expected >=3 invariant robustness cases, saw {invariant}"
    );
}

/// Rebuild targets from a case's raw per-sample labels/values through the same
/// sorted-unique encoding sklearn used.
fn build_targets(c: &ForestAggregateCase) -> Targets {
    match c.task.as_str() {
        "classification" => {
            let labels = c.labels.as_ref().expect("classification carries labels");
            Targets::categorical(labels).expect("valid labels")
        }
        "regression" => {
            let values = c.values.as_ref().expect("regression carries values");
            Targets::numeric(values).expect("valid values")
        }
        other => panic!("unexpected task {other}"),
    }
}

/// Robustness assertions (no score band): valid probability rows / in-range class
/// indices / finite regression predictions, and finite importances.
fn assert_invariants(
    id: &str,
    forest: &RandomForest,
    x_test: &FeatureMatrix,
    c: &ForestAggregateCase,
) {
    let fi = forest.feature_importances();
    assert!(
        fi.iter().all(|v| v.is_finite()),
        "{id}: non-finite importance"
    );
    assert_eq!(fi.len(), c.data_coo.n_features, "{id}: importance length");
    match forest.task() {
        Task::Classification { n_classes } => {
            let proba = forest.predict_proba(x_test).unwrap();
            for row in &proba {
                assert_eq!(row.len(), n_classes, "{id}: proba width");
                let s: f64 = row.iter().sum();
                assert!((s - 1.0).abs() < 1e-9, "{id}: proba row sums to {s}");
                assert!(
                    row.iter().all(|p| (0.0..=1.0).contains(p)),
                    "{id}: proba out of [0,1]"
                );
            }
            for idx in forest.predict_class_indices(x_test).unwrap() {
                assert!(idx < n_classes, "{id}: class index {idx} >= {n_classes}");
            }
        }
        Task::Regression => {
            for v in forest.predict_values(x_test).unwrap() {
                assert!(v.is_finite(), "{id}: non-finite prediction");
            }
        }
    }
}

/// Spearman rank correlation: Pearson over average-tie ranks (scipy `rankdata`
/// default), matching how the generator computed the fixture's floor.
fn spearman(a: &[f64], b: &[f64]) -> f64 {
    pearson(&average_ranks(a), &average_ranks(b))
}

/// Pearson correlation of two equal-length slices, clamped to `[-1, 1]` and
/// returning `0.0` when either side is constant — the same convention
/// `metrics::linear_regress` uses, but without its `n >= 3` regression-diagnostic
/// precondition (this is a plain correlation over feature-importance ranks).
fn pearson(x: &[f64], y: &[f64]) -> f64 {
    assert_eq!(x.len(), y.len(), "pearson: length mismatch");
    let n = x.len() as f64;
    let xm = x.iter().sum::<f64>() / n;
    let ym = y.iter().sum::<f64>() / n;
    let (mut sxx, mut syy, mut sxy) = (0.0, 0.0, 0.0);
    for (&xi, &yi) in x.iter().zip(y) {
        let (dx, dy) = (xi - xm, yi - ym);
        sxx += dx * dx;
        syy += dy * dy;
        sxy += dx * dy;
    }
    if sxx == 0.0 || syy == 0.0 {
        return 0.0;
    }
    (sxy / (sxx * syy).sqrt()).clamp(-1.0, 1.0)
}

/// Fractional ranks with ties broken by their average position (1-based),
/// reproducing `scipy.stats.rankdata(method="average")`.
fn average_ranks(v: &[f64]) -> Vec<f64> {
    let n = v.len();
    let mut order: Vec<usize> = (0..n).collect();
    order.sort_by(|&i, &j| v[i].partial_cmp(&v[j]).expect("finite importances"));
    let mut ranks = vec![0.0f64; n];
    let mut i = 0;
    while i < n {
        let mut j = i + 1;
        while j < n && v[order[j]] == v[order[i]] {
            j += 1;
        }
        // 1-based positions (i+1)..=j average to ((i+1)+j)/2.
        let avg = ((i + 1 + j) as f64) / 2.0;
        for &pos in &order[i..j] {
            ranks[pos] = avg;
        }
        i = j;
    }
    ranks
}

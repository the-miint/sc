//! Oracle tests for the M4 RandomForest, both tiers.
//!
//! **TIGHT import** (`forest_classifier` / `forest_regressor`, tol 1e-9): rebuild
//! each fixture's forest by importing every tree via [`Tree::from_sklearn`] into a
//! [`RandomForest`], then assert forest-level `predict` / `predict_proba` /
//! `predict_values` / `feature_importances_` reproduce scikit-learn exactly. These
//! are the empirical arbiters for the aggregation math (soft-vote, mean-of-trees,
//! summed-normalized MDI).
//!
//! **AGGREGATE** (`forest_aggregate`): fit our own forest on a fixed injected
//! split and assert the test score lands inside a band calibrated from sklearn's
//! seed-to-seed spread (widened by a margin, since our RNG-driven build is not
//! sklearn-exact), plus a Spearman rank-correlation floor on the importances.
//! Robustness cases (`metric == "invariant"`) assert shape invariants only.
//!
//! Hermetic: no Python, no network — just the committed fixtures generated by
//! `oracle/generator/gen_forest.py` against `qiime2-amplicon-2024.10`.

use sc_core::metrics::{accuracy, linear_regress};
use sc_core::{FeatureMatrix, RandomForest, RandomForestParams, Targets, Task, Tree};
use sc_oracle::{load_dir, CooTable, ForestAggregateCase, OracleCase, Payload};

fn fixtures() -> Vec<OracleCase> {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../oracle/fixtures/forest");
    let cases = load_dir(dir);
    assert!(!cases.is_empty(), "no fixtures loaded from {dir}");
    cases
}

fn query_matrix(coo: &CooTable) -> FeatureMatrix {
    FeatureMatrix::from_coo(
        coo.n_samples,
        coo.n_features,
        &coo.rows,
        &coo.cols,
        &coo.vals,
    )
    .expect("valid COO")
}

#[test]
fn classifier_import_matches_oracle() {
    let mut n = 0;
    for case in fixtures() {
        let Payload::ForestClassifier(c) = &case.payload else {
            continue;
        };
        n += 1;
        let (id, tol) = (&case.id, &case.tolerance);
        let trees: Vec<Tree> = c
            .trees
            .iter()
            .map(|t| {
                let value: Vec<f64> = t.value.iter().flatten().copied().collect();
                Tree::from_sklearn(
                    Task::Classification {
                        n_classes: c.n_classes,
                    },
                    &t.children_left,
                    &t.children_right,
                    &t.feature,
                    &t.threshold,
                    &value,
                    &t.impurity,
                    &t.n_node_samples,
                    &t.weighted_n_node_samples,
                    c.n_features,
                )
                .unwrap_or_else(|e| panic!("{id}: from_sklearn failed: {e}"))
            })
            .collect();
        let forest = RandomForest::from_trees(trees, Some(c.classes.clone()))
            .unwrap_or_else(|e| panic!("{id}: from_trees failed: {e}"));
        assert_eq!(forest.n_trees(), c.trees.len(), "{id}: tree count");

        let x = query_matrix(&c.test_coo);
        assert_eq!(
            forest.predict_class_indices(&x).unwrap(),
            c.expected.predict,
            "{id}: predict"
        );
        let proba = forest.predict_proba(&x).unwrap();
        assert_eq!(proba.len(), c.expected.proba.len(), "{id}: proba rows");
        for (i, (g, e)) in proba.iter().zip(&c.expected.proba).enumerate() {
            sc_oracle::assert_close_slice(g, e, tol, &format!("{id}: proba[{i}]"));
        }
        sc_oracle::assert_close_slice(
            &forest.feature_importances(),
            &c.expected.mdi,
            tol,
            &format!("{id}: mdi"),
        );
    }
    assert!(n >= 2, "expected >=2 forest classifier fixtures, saw {n}");
}


//! Oracle tests for the M8 nested/OOF cross-validation (AGGREGATE tier).
//!
//! Each fixture injects q2's exact outer folds (a per-sample `fold_ids` array,
//! rebuilt into a [`CvFolds`] via [`CvFolds::from_fold_ids`]) so q2 and our forest
//! cross-validate the *same* partition. We run [`ncv_with_folds`] (`tuning=None`,
//! q2's default) and assert the **overall** OOF score lands inside a band
//! calibrated from sklearn's seed-to-seed spread (widened by a margin, since our
//! RNG-driven forest is not sklearn-exact): `accuracy_score(y, oof)`
//! (classification); squared-Pearson r² + MSE via the `linear_regress` formula
//! (regression) — the same overall metric M4's `forest_aggregate` uses. Plus a
//! Spearman rank-correlation floor on the fold-averaged importances, and the
//! structural OOF invariants (every sample predicted exactly once; proba rows are
//! full-width and sum to 1).
//!
//! The per-fold `mean_score`/`std_score` q2 prints are pinned by the determinism
//! golden (`tests/determinism.rs`), not here — the low-variance overall-OOF score
//! is the parity target.
//!
//! Hermetic: no Python, no network — just the committed fixtures generated by
//! `oracle/generator/gen_ncv.py` against `qiime2-amplicon-2024.10`.

use sc_core::metrics::{accuracy, linear_regress};
use sc_core::{ncv_with_folds, CvFolds, FeatureMatrix, NcvParams, OofPredictions, Targets};
use sc_oracle::{load_dir, CooTable, NcvAggregateCase, OracleCase, Payload};

fn fixtures() -> Vec<OracleCase> {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../oracle/fixtures/ncv");
    let cases = load_dir(dir);
    assert!(!cases.is_empty(), "no fixtures loaded from {dir}");
    cases
}

fn query_matrix(coo: &CooTable) -> FeatureMatrix {
    FeatureMatrix::from_coo(
        coo.n_samples,
        coo.n_features,
        &coo.rows,
        &coo.cols,
        &coo.vals,
    )
    .expect("valid COO")
}

/// Rebuild targets from a case's raw per-sample labels/values through the same
/// sorted-unique encoding sklearn used.
fn build_targets(c: &NcvAggregateCase) -> Targets {
    match c.task.as_str() {
        "classification" => {
            let labels = c.labels.as_ref().expect("classification carries labels");
            Targets::categorical(labels).expect("valid labels")
        }
        "regression" => {
            let values = c.values.as_ref().expect("regression carries values");
            Targets::numeric(values).expect("valid values")
        }
        other => panic!("unexpected task {other}"),
    }
}

#[test]
fn ncv_oof_scores_within_calibrated_band() {
    let mut classification = 0;
    let mut regression = 0;
    for case in fixtures() {
        let Payload::NcvAggregate(c) = &case.payload else {
            continue;
        };
        let id = &case.id;
        let x = query_matrix(&c.data_coo);
        let y = build_targets(c);
        let folds = CvFolds::from_fold_ids(&c.fold_ids, c.n_splits)
            .unwrap_or_else(|e| panic!("{id}: from_fold_ids failed: {e}"));

        let mut params = match c.task.as_str() {
            "classification" => NcvParams::classifier_defaults(),
            "regression" => NcvParams::regressor_defaults(),
            other => panic!("{id}: unexpected task {other}"),
        };
        params.forest.n_estimators = c.n_estimators;
        // `params.n_splits` is intentionally left at its default: `ncv_with_folds`
        // keys everything off the injected `folds.n_splits()` and never reads it.

        // Deterministic under a fixed master seed → the whole test is deterministic.
        let result = ncv_with_folds(&x, &y, &params, &folds, 0)
            .unwrap_or_else(|e| panic!("{id}: ncv failed: {e}"));

        // Structural invariants + the task's overall OOF score.
        match &result.predictions {
            OofPredictions::Classification {
                classes,
                codes,
                proba,
            } => {
                classification += 1;
                let n = c.data_coo.n_samples;
                let n_classes = classes.len();
                assert_eq!(codes.len(), n, "{id}: one OOF code per sample");
                assert_eq!(proba.len(), n, "{id}: one OOF proba row per sample");
                for (i, row) in proba.iter().enumerate() {
                    assert_eq!(row.len(), n_classes, "{id}: proba[{i}] width");
                    let s: f64 = row.iter().sum();
                    assert!((s - 1.0).abs() < 1e-9, "{id}: proba[{i}] sums to {s}");
                    assert!(
                        row.iter().all(|p| (0.0..=1.0).contains(p)),
                        "{id}: proba[{i}] out of [0,1]"
                    );
                }
                assert!(
                    codes.iter().all(|&code| code < n_classes),
                    "{id}: OOF code out of range"
                );

                // Overall accuracy vs the calibrated band (accuracy_score(y, oof)).
                let truth = y.codes().expect("categorical codes");
                let acc = accuracy(truth, codes);
                assert!(
                    c.band.contains(acc),
                    "{id}: OOF accuracy {acc:.4} outside band [{}, {}] (+/- margin {})",
                    c.band.min,
                    c.band.max,
                    c.band.margin_abs
                );
            }
            OofPredictions::Regression { values } => {
                regression += 1;
                let n = c.data_coo.n_samples;
                assert_eq!(values.len(), n, "{id}: one OOF value per sample");
                assert!(
                    values.iter().all(|v| v.is_finite()),
                    "{id}: non-finite OOF value"
                );
                let Targets::Numeric(truth) = &y else {
                    panic!("{id}: expected numeric targets");
                };
                // Overall r²+mse computed exactly as the generator (linear_regress).
                let rep = linear_regress(truth, values);
                assert!(
                    c.band.contains(rep.r_squared),
                    "{id}: OOF r2 {:.4} outside band [{}, {}]",
                    rep.r_squared,
                    c.band.min,
                    c.band.max
                );
                let mse_band = c.mse_band.as_ref().expect("regression carries an mse band");
                assert!(
                    mse_band.contains(rep.mse),
                    "{id}: OOF mse {:.4} outside band [{}, {}]",
                    rep.mse,
                    mse_band.min,
                    mse_band.max
                );
            }
        }

        // Fold-averaged importance ranking is rank-correlated with sklearn's
        // seed-mean of the same quantity.
        let rho = spearman(&result.importances, &c.ref_importances);
        let floor = c.rank_corr_floor - c.rank_corr_margin;
        assert!(
            rho >= floor,
            "{id}: importance rank-corr {rho:.4} < floor {floor:.4} \
             (sklearn min-pairwise {:.4} - margin {})",
            c.rank_corr_floor,
            c.rank_corr_margin
        );
    }
    assert!(
        classification >= 2,
        "expected >=2 classification ncv cases, saw {classification}"
    );
    assert!(
        regression >= 2,
        "expected >=2 regression ncv cases, saw {regression}"
    );
}

/// Spearman rank correlation: Pearson over average-tie ranks (scipy `rankdata`
/// default), matching how the generator computed the fixture's floor.
fn spearman(a: &[f64], b: &[f64]) -> f64 {
    pearson(&average_ranks(a), &average_ranks(b))
}

/// Pearson correlation of two equal-length slices, clamped to `[-1, 1]` and
/// returning `0.0` when either side is constant.
fn pearson(x: &[f64], y: &[f64]) -> f64 {
    assert_eq!(x.len(), y.len(), "pearson: length mismatch");
    let n = x.len() as f64;
    let xm = x.iter().sum::<f64>() / n;
    let ym = y.iter().sum::<f64>() / n;
    let (mut sxx, mut syy, mut sxy) = (0.0, 0.0, 0.0);
    for (&xi, &yi) in x.iter().zip(y) {
        let (dx, dy) = (xi - xm, yi - ym);
        sxx += dx * dx;
        syy += dy * dy;
        sxy += dx * dy;
    }
    if sxx == 0.0 || syy == 0.0 {
        return 0.0;
    }
    (sxy / (sxx * syy).sqrt()).clamp(-1.0, 1.0)
}

/// Fractional ranks with ties broken by their average position (1-based),
/// reproducing `scipy.stats.rankdata(method="average")`.
fn average_ranks(v: &[f64]) -> Vec<f64> {
    let n = v.len();
    let mut order: Vec<usize> = (0..n).collect();
    order.sort_by(|&i, &j| v[i].partial_cmp(&v[j]).expect("finite importances"));
    let mut ranks = vec![0.0f64; n];
    let mut i = 0;
    while i < n {
        let mut j = i + 1;
        while j < n && v[order[j]] == v[order[i]] {
            j += 1;
        }
        let avg = ((i + 1 + j) as f64) / 2.0;
        for &pos in &order[i..j] {
            ranks[pos] = avg;
        }
        i = j;
    }
    ranks
}
